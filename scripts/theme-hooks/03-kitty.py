#!/usr/bin/env python3
"""GPS Theme Hook: Synchronize Kitty terminal color scheme and reload running instances."""
from __future__ import annotations

import os
from pathlib import Path
import re
import signal
import subprocess
import sys
from typing import Any

# Add parent directory for theme_common
script_dir = Path(__file__).resolve().parent
parent_dir = script_dir.parent
if str(parent_dir) not in sys.path:
    sys.path.insert(0, str(parent_dir))

import theme_common


GPS_BLOCK_START = "# --- BEGIN GPS THEME (DO NOT EDIT) ---"
GPS_BLOCK_END = "# --- END GPS THEME ---"
GPS_INCLUDE_STMT = "include gps-theme.conf"


def generate_kitty_theme(theme: dict[str, Any]) -> str:
    """Generate Kitty configuration string with contrast-protected tokens."""
    # Ensure minimum contrast >= 4.5:1 for normal text
    bg = theme_common.to_hex6(theme.get("surfaceDeep", theme.get("track", "#0F131C")))
    fg = theme_common.to_hex6(theme.get("textMain", "#DFE2EF"))

    if not theme_common.is_contrast_sufficient(fg, bg, 4.5):
        # Fall back to safe white or fallback foreground
        fg = "#FFFFFF" if theme_common.is_contrast_sufficient("#FFFFFF", bg, 4.5) else "#DFE2EF"

    accent = theme_common.to_hex6(theme.get("brandAccent", "#2DD4BF"))
    accent_fg = theme_common.to_hex6(theme.get("brandAccentFg", "#003731"))
    card = theme_common.to_hex6(theme.get("card", "#1C1F29"))
    card_hover = theme_common.to_hex6(theme.get("cardHover", "#262A34"))
    border_col = theme_common.to_hex6(theme.get("border", "#3C4A46"))
    text_muted = theme_common.to_hex6(theme.get("textMuted", "#BACAC5"))

    # ANSI palette derived from theme tokens and status constants
    color0 = bg                                 # Black
    color8 = border_col                         # Bright Black / Gray
    color1 = "#FF5C77"                          # Red (statusDanger)
    color9 = "#FF8095"                          # Bright Red
    color2 = "#9CE5C0"                          # Green (statusGood)
    color10 = "#B5EED0"                         # Bright Green
    color3 = "#FFD47B"                          # Yellow (statusWarn)
    color11 = "#FFE09E"                         # Bright Yellow
    color4 = accent                             # Blue / Primary Accent
    color12 = theme.get("accentPrimary", accent) # Bright Blue / Primary Accent
    color5 = "#DDB8FF"                          # Magenta / Secondary Accent
    color13 = "#E8D0FF"                         # Bright Magenta
    color6 = "#57F1DB"                          # Cyan
    color14 = "#85F6E6"                         # Bright Cyan
    color7 = text_muted                         # White / Subdued
    color15 = fg                                # Bright White / Main Text

    return f"""# Generated by GPS Theme System — do not edit manually.

# Core terminal colors
background            {bg}
foreground            {fg}
selection_background   {card_hover}
selection_foreground   {fg}
cursor                {accent}
cursor_text_color     {accent_fg}
url_color             {accent}

# Standard ANSI colors
color0   {color0}
color1   {color1}
color2   {color2}
color3   {color3}
color4   {color4}
color5   {color5}
color6   {color6}
color7   {color7}

# Bright ANSI colors
color8   {color8}
color9   {color9}
color10  {color10}
color11  {color11}
color12  {color12}
color13  {color13}
color14  {color14}
color15  {color15}
"""


def integrate_kitty_conf(kitty_dir: Path, theme_conf_content: str) -> None:
    """Write gps-theme.conf atomically and ensure kitty.conf includes it cleanly."""
    kitty_dir.mkdir(parents=True, exist_ok=True)
    theme_conf_path = kitty_dir / "gps-theme.conf"
    kitty_conf_path = kitty_dir / "kitty.conf"

    # 1. Atomically write gps-theme.conf
    theme_common.atomic_write(theme_conf_path, theme_conf_content)

    # 2. Back up kitty.conf once before initial integration
    theme_common.backup_file_once(kitty_conf_path)

    # 3. Read existing kitty.conf or start empty
    existing_content = ""
    if kitty_conf_path.is_file():
        try:
            existing_content = kitty_conf_path.read_text(encoding="utf-8")
        except OSError:
            existing_content = ""

    # Check if include is already in existing configuration outside GPS block
    lines = [line.strip() for line in existing_content.splitlines()]
    if any(line == GPS_INCLUDE_STMT for line in lines):
        return

    gps_block = f"{GPS_BLOCK_START}\n{GPS_INCLUDE_STMT}\n{GPS_BLOCK_END}"
    block_pattern = re.compile(
        re.escape(GPS_BLOCK_START) + r".*?" + re.escape(GPS_BLOCK_END),
        re.DOTALL,
    )
    if block_pattern.search(existing_content):
        new_conf = block_pattern.sub(gps_block, existing_content)
    else:
        trimmed = existing_content.rstrip()
        if trimmed:
            new_conf = f"{trimmed}\n\n{gps_block}\n"
        else:
            new_conf = f"{gps_block}\n"

    theme_common.atomic_write(kitty_conf_path, new_conf)


def reload_running_kitties() -> int:
    """Send SIGUSR1 to all running Kitty instances owned by current user."""
    reloaded_count = 0
    try:
        # Use pgrep to find kitty processes owned by current user
        current_uid = os.getuid()
        out = subprocess.check_output(
            ["pgrep", "-u", str(current_uid), "-x", "kitty"],
            text=True,
            stderr=subprocess.DEVNULL,
        )
        for line in out.splitlines():
            pid_str = line.strip()
            if pid_str.isdigit():
                pid = int(pid_str)
                try:
                    os.kill(pid, signal.SIGUSR1)
                    reloaded_count += 1
                except OSError:
                    pass
    except subprocess.CalledProcessError:
        # No kitty processes found
        pass
    except Exception:
        pass
    return reloaded_count


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    if not args:
        print("Usage: 03-kitty.py <path-to-gps-theme.json>", file=sys.stderr)
        return 1

    palette_path = Path(args[0]).expanduser().resolve()
    theme, is_valid = theme_common.load_and_validate_palette(palette_path)

    config_root = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config"))
    kitty_dir = config_root / "kitty"

    theme_content = generate_kitty_theme(theme)
    integrate_kitty_conf(kitty_dir, theme_content)

    reloaded = reload_running_kitties()
    print(f"Synchronized Kitty palette (reloaded {reloaded} running instances, fallback={not is_valid})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
