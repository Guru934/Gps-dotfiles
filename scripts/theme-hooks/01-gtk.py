#!/usr/bin/env python3
"""GPS Theme Hook: Synchronize GTK 3 and GTK 4 / libadwaita palettes."""
from __future__ import annotations

import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any

# Add parent directory for theme_common
script_dir = Path(__file__).resolve().parent
parent_dir = script_dir.parent
if str(parent_dir) not in sys.path:
    sys.path.insert(0, str(parent_dir))

import theme_common


GPS_BLOCK_START = "/* --- BEGIN GPS THEME (DO NOT EDIT) --- */"
GPS_BLOCK_END = "/* --- END GPS THEME --- */"
GPS_IMPORT_STMT = '@import url("gps-theme.css");'


def generate_gtk_css(theme: dict[str, Any]) -> str:
    """Generate CSS with libadwaita named colors and GTK 3 theme tokens."""
    accent = theme_common.to_hex6(theme.get("brandAccent", "#2DD4BF"))
    accent_fg = theme_common.to_hex6(theme.get("brandAccentFg", "#003731"))
    text_main = theme_common.to_hex6(theme.get("textMain", "#DFE2EF"))
    text_muted = theme_common.to_hex6(theme.get("textMuted", "#BACAC5"))

    # Background surfaces
    window_bg = theme_common.to_hex6(theme.get("surfaceDeep", theme.get("track", "#0F131C")))
    view_bg = theme_common.to_hex6(theme.get("track", "#0B1016"))
    headerbar_bg = theme_common.to_hex6(theme.get("card", "#1C1F29"))
    card_bg = theme_common.to_hex6(theme.get("card", "#1C1F29"))
    card_hover = theme_common.to_hex6(theme.get("cardHover", "#262A34"))
    border_col = theme_common.to_hex6(theme.get("border", "#3C4A46"))

    return f"""/* Generated by GPS Theme System — do not edit manually. */

/* ──────────────── libadwaita / GTK 4 named colors ──────────────── */
@define-color accent_color {accent};
@define-color accent_bg_color {accent};
@define-color accent_fg_color {accent_fg};
@define-color window_bg_color {window_bg};
@define-color window_fg_color {text_main};
@define-color view_bg_color {view_bg};
@define-color view_fg_color {text_main};
@define-color headerbar_bg_color {headerbar_bg};
@define-color headerbar_fg_color {text_main};
@define-color headerbar_border_color {border_col};
@define-color headerbar_backdrop_color {window_bg};
@define-color card_bg_color {card_bg};
@define-color card_fg_color {text_main};
@define-color card_border_color {border_col};
@define-color popover_bg_color {card_bg};
@define-color popover_fg_color {text_main};
@define-color dialog_bg_color {card_bg};
@define-color dialog_fg_color {text_main};
@define-color secondary_bg_color {card_hover};
@define-color secondary_fg_color {text_muted};
@define-color border_color {border_col};
@define-color shade_color rgba(0, 0, 0, 0.36);
@define-color scrollbar_outline_color rgba(0, 0, 0, 0.50);

/* ──────────────── GTK 3 Theme definitions ──────────────── */
@define-color theme_selected_bg_color {accent};
@define-color theme_selected_fg_color {accent_fg};
@define-color theme_bg_color {window_bg};
@define-color theme_fg_color {text_main};
@define-color theme_base_color {view_bg};
@define-color theme_text_color {text_main};
@define-color theme_unfocused_bg_color {window_bg};
@define-color theme_unfocused_fg_color {text_muted};
@define-color theme_unfocused_base_color {view_bg};
@define-color theme_unfocused_text_color {text_muted};
@define-color theme_unfocused_selected_bg_color {accent};
@define-color theme_unfocused_selected_fg_color {accent_fg};
@define-color borders {border_col};

/* ──────────────── GTK 3 Core Widget Rules ──────────────── */
window, .background {{
    background-color: @theme_bg_color;
    color: @theme_fg_color;
}}

headerbar {{
    background-color: @headerbar_bg_color;
    color: @headerbar_fg_color;
    border-color: @border_color;
}}

treeview, .view {{
    background-color: @theme_base_color;
    color: @theme_text_color;
}}

.view:selected, treeview:selected, :selected {{
    background-color: @theme_selected_bg_color;
    color: @theme_selected_fg_color;
}}
"""


def integrate_gtk_css(target_dir: Path, css_content: str) -> None:
    """Write gps-theme.css atomically and ensure gtk.css imports it cleanly."""
    target_dir.mkdir(parents=True, exist_ok=True)
    gps_css_path = target_dir / "gps-theme.css"
    gtk_css_path = target_dir / "gtk.css"

    # 1. Atomically write gps-theme.css
    theme_common.atomic_write(gps_css_path, css_content)

    # 2. Back up gtk.css once before initial GPS integration
    theme_common.backup_file_once(gtk_css_path)

    # 3. Read existing gtk.css or start empty
    existing_content = ""
    if gtk_css_path.is_file():
        try:
            existing_content = gtk_css_path.read_text(encoding="utf-8")
        except OSError:
            existing_content = ""

    gps_block = f"{GPS_BLOCK_START}\n{GPS_IMPORT_STMT}\n{GPS_BLOCK_END}"

    # Replace existing GPS block if present, or append
    block_pattern = re.compile(
        re.escape(GPS_BLOCK_START) + r".*?" + re.escape(GPS_BLOCK_END),
        re.DOTALL,
    )
    if block_pattern.search(existing_content):
        new_gtk_css = block_pattern.sub(gps_block, existing_content)
    else:
        trimmed = existing_content.rstrip()
        if trimmed:
            new_gtk_css = f"{trimmed}\n\n{gps_block}\n"
        else:
            new_gtk_css = f"{gps_block}\n"

    theme_common.atomic_write(gtk_css_path, new_gtk_css)


def check_and_set_gsettings_dark() -> None:
    """Ensure GNOME/GTK dark mode preference via gsettings."""
    schema = "org.gnome.desktop.interface"
    key = "color-scheme"
    try:
        check = subprocess.run(
            ["gsettings", "get", schema, key],
            capture_output=True,
            text=True,
            timeout=2,
        )
        if check.returncode == 0:
            current = check.stdout.strip().strip("'\"")
            if current != "prefer-dark":
                subprocess.run(
                    ["gsettings", "set", schema, key, "prefer-dark"],
                    capture_output=True,
                    timeout=2,
                )
    except Exception:
        # Graceful fallback if gsettings is unavailable or schema missing
        pass


def check_adw_gtk3() -> bool:
    """Verify if adw-gtk3 theme is installed."""
    for theme_dir in [Path("/usr/share/themes/adw-gtk3"), Path("/usr/share/themes/adw-gtk3-dark")]:
        if theme_dir.is_dir():
            return True
    user_theme = Path.home() / ".themes" / "adw-gtk3"
    if user_theme.is_dir():
        return True
    return False


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    if not args:
        print("Usage: 01-gtk.py <path-to-gps-theme.json>", file=sys.stderr)
        return 1

    palette_path = Path(args[0]).expanduser().resolve()
    theme, is_valid = theme_common.load_and_validate_palette(palette_path)

    css_content = generate_gtk_css(theme)

    config_root = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config"))
    gtk3_dir = config_root / "gtk-3.0"
    gtk4_dir = config_root / "gtk-4.0"

    integrate_gtk_css(gtk3_dir, css_content)
    integrate_gtk_css(gtk4_dir, css_content)

    check_and_set_gsettings_dark()

    if not check_adw_gtk3():
        print(
            "Note: adw-gtk3 theme not found. For full GTK 3 libadwaita styling, "
            "install via: sudo pacman -S adw-gtk-theme",
            file=sys.stderr,
        )

    print(f"Synchronized GTK 3 and GTK 4 palettes (fallback={not is_valid})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
