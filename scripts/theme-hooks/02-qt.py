#!/usr/bin/env python3
"""GPS Theme Hook: Synchronize Qt (qt6ct) color scheme and configuration."""
from __future__ import annotations

import configparser
import os
from pathlib import Path
import shutil
import sys
from typing import Any

# Add parent directory for theme_common
script_dir = Path(__file__).resolve().parent
parent_dir = script_dir.parent
if str(parent_dir) not in sys.path:
    sys.path.insert(0, str(parent_dir))

import theme_common


def generate_qt6ct_palette(theme: dict[str, Any]) -> str:
    """Generate 20-role qt6ct ColorScheme INI content using #aarrggbb format."""
    text_main = theme_common.to_hex8_argb(theme.get("textMain", "#DFE2EF"))
    text_muted = theme_common.to_hex8_argb(theme.get("textMuted", "#BACAC5"))
    bright_text = "#ffffffff"
    shadow = "#ff000000"

    card = theme_common.to_hex8_argb(theme.get("card", "#1C1F29"))
    card_hover = theme_common.to_hex8_argb(theme.get("cardHover", "#262A34"))
    track = theme_common.to_hex8_argb(theme.get("track", "#0B1016"))
    window_bg = theme_common.to_hex8_argb(theme.get("surfaceDeep", theme.get("track", "#0F131C")))
    border_col = theme_common.to_hex8_argb(theme.get("border", "#3C4A46"))

    accent = theme_common.to_hex8_argb(theme.get("brandAccent", "#2DD4BF"))
    accent_fg = theme_common.to_hex8_argb(theme.get("brandAccentFg", "#003731"))

    # Active roles (1 to 20):
    # 1: WindowText, 2: Button, 3: Light, 4: Midlight, 5: Dark, 6: Mid, 7: Text, 8: BrightText,
    # 9: ButtonText, 10: Base, 11: Window, 12: Shadow, 13: Highlight, 14: HighlightedText,
    # 15: Link, 16: LinkVisited, 17: AlternateBase, 18: NoRole, 19: ToolTipBase, 20: ToolTipText
    active = [
        text_main,    # 1: WindowText
        card,         # 2: Button
        card_hover,   # 3: Light
        card,         # 4: Midlight
        track,        # 5: Dark
        border_col,   # 6: Mid
        text_main,    # 7: Text
        bright_text,  # 8: BrightText
        text_main,    # 9: ButtonText
        track,        # 10: Base
        window_bg,    # 11: Window
        shadow,       # 12: Shadow
        accent,       # 13: Highlight
        accent_fg,    # 14: HighlightedText
        accent,       # 15: Link
        text_muted,   # 16: LinkVisited
        card,         # 17: AlternateBase
        card,         # 18: NoRole
        card,         # 19: ToolTipBase
        text_main,    # 20: ToolTipText
    ]

    # Disabled roles (muted typography and dimmed highlight)
    disabled = [
        text_muted,   # 1: WindowText
        card,         # 2: Button
        card_hover,   # 3: Light
        card,         # 4: Midlight
        track,        # 5: Dark
        border_col,   # 6: Mid
        text_muted,   # 7: Text
        text_muted,   # 8: BrightText
        text_muted,   # 9: ButtonText
        track,        # 10: Base
        window_bg,    # 11: Window
        shadow,       # 12: Shadow
        border_col,   # 13: Highlight
        text_muted,   # 14: HighlightedText
        text_muted,   # 15: Link
        text_muted,   # 16: LinkVisited
        card,         # 17: AlternateBase
        card,         # 18: NoRole
        card,         # 19: ToolTipBase
        text_muted,   # 20: ToolTipText
    ]

    active_str = ", ".join(active)
    disabled_str = ", ".join(disabled)

    return (
        "# Generated by GPS Theme System — do not edit manually.\n"
        "[ColorScheme]\n"
        f"active_colors={active_str}\n"
        f"inactive_colors={active_str}\n"
        f"disabled_colors={disabled_str}\n"
    )


def update_qt6ct_config(qt6ct_conf_path: Path, scheme_path: Path) -> None:
    """Update qt6ct.conf [Appearance] section while preserving other configurations."""
    theme_common.backup_file_once(qt6ct_conf_path)

    config = configparser.RawConfigParser()
    if qt6ct_conf_path.is_file():
        try:
            config.read(str(qt6ct_conf_path), encoding="utf-8")
        except Exception:
            pass

    if not config.has_section("Appearance"):
        config.add_section("Appearance")

    config.set("Appearance", "color_scheme_path", str(scheme_path))
    config.set("Appearance", "custom_palette", "true")
    if not config.has_option("Appearance", "style"):
        config.set("Appearance", "style", "Fusion")
    if not config.has_option("Appearance", "standard_dialogs"):
        config.set("Appearance", "standard_dialogs", "default")

    from io import StringIO
    sio = StringIO()
    config.write(sio)
    theme_common.atomic_write(qt6ct_conf_path, sio.getvalue())


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    if not args:
        print("Usage: 02-qt.py <path-to-gps-theme.json>", file=sys.stderr)
        return 1

    palette_path = Path(args[0]).expanduser().resolve()
    theme, is_valid = theme_common.load_and_validate_palette(palette_path)

    config_root = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config"))
    qt6ct_dir = config_root / "qt6ct"
    colors_dir = qt6ct_dir / "colors"
    colors_dir.mkdir(parents=True, exist_ok=True)

    scheme_path = colors_dir / "gps-theme.conf"
    scheme_content = generate_qt6ct_palette(theme)
    theme_common.atomic_write(scheme_path, scheme_content)

    qt6ct_conf = qt6ct_dir / "qt6ct.conf"
    update_qt6ct_config(qt6ct_conf, scheme_path)

    if shutil.which("qt6ct") is None:
        print(
            f"Generated Qt color scheme at {scheme_path}. "
            "Note: qt6ct utility is not installed. To activate dynamically for Qt apps, "
            "install qt6ct (sudo pacman -S qt6ct) and set QT_QPA_PLATFORMTHEME=qt6ct.",
            file=sys.stderr,
        )

    print(f"Synchronized Qt palette at {scheme_path} (fallback={not is_valid})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
