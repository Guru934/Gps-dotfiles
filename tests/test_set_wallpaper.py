import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch, MagicMock
from types import SimpleNamespace
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
import sys
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))

import set_wallpaper


class SetWallpaperPipelineTests(unittest.TestCase):
    def setUp(self):
        self.tmp_dir = tempfile.TemporaryDirectory()
        self.tmp_path = Path(self.tmp_dir.name)
        self.test_img = self.tmp_path / "test_wall.png"
        img = Image.new("RGB", (100, 100), color=(45, 212, 191))
        img.save(self.test_img)

        self.last_wall = self.tmp_path / "gps-last-wall.txt"
        self.theme_json = self.tmp_path / "gps-theme.json"
        self.rofi_rasi = self.tmp_path / "rofi" / "colors.rasi"
        self.rofi_rasi.parent.mkdir(parents=True, exist_ok=True)

    def tearDown(self):
        self.tmp_dir.cleanup()

    def test_atomic_write_creates_file_and_cleans_temp(self):
        target = self.tmp_path / "atomic.txt"
        content = "hello atomic world\n"
        set_wallpaper.atomic_write(target, content)
        self.assertTrue(target.exists())
        self.assertEqual(target.read_text(encoding="utf-8"), content)
        # Ensure no temp files left behind
        temp_files = list(self.tmp_path.glob(".*atomic.txt.tmp-*"))
        self.assertEqual(len(temp_files), 0)

    def test_apply_wallpaper_success(self):
        run_mock = MagicMock(return_value=SimpleNamespace(returncode=0, stdout="", stderr=""))
        with patch.object(set_wallpaper, "ensure_awww_daemon", return_value=True), \
             patch.object(set_wallpaper.subprocess, "run", run_mock), \
             patch.dict(os.environ, {"HYPRLAND_INSTANCE_SIGNATURE": ""}):
            result = set_wallpaper.apply_wallpaper(
                self.test_img,
                last_wall_path=self.last_wall,
                theme_json_path=self.theme_json,
                rofi_path=self.rofi_rasi,
            )

        self.assertTrue(result.get("ok"))
        self.assertEqual(result.get("wallpaper"), str(self.test_img.resolve()))
        self.assertTrue(self.last_wall.exists())
        self.assertEqual(self.last_wall.read_text(encoding="utf-8").strip(), str(self.test_img.resolve()))

        self.assertTrue(self.theme_json.exists())
        theme_data = json.loads(self.theme_json.read_text(encoding="utf-8"))
        for required_key in ["wallpaper", "surface", "card", "cardHover", "track", "border", "brandAccent", "brandAccentFg", "textMain", "textMuted"]:
            self.assertIn(required_key, theme_data)
            self.assertTrue(theme_data[required_key])

        # Rofi colors.rasi must also be created
        self.assertTrue(self.rofi_rasi.exists())
        rasi_content = self.rofi_rasi.read_text(encoding="utf-8")
        self.assertIn("/* Generated by scripts/set-wallpaper", rasi_content)
        self.assertIn("accent:", rasi_content)

    def test_apply_wallpaper_missing_file_fails_without_corrupting(self):
        non_existent = self.tmp_path / "does_not_exist.png"
        result = set_wallpaper.apply_wallpaper(
            non_existent,
            last_wall_path=self.last_wall,
            theme_json_path=self.theme_json,
            rofi_path=self.rofi_rasi,
        )
        self.assertFalse(result.get("ok"))
        self.assertIn("not found", result.get("error", ""))
        self.assertFalse(self.last_wall.exists())
        self.assertFalse(self.theme_json.exists())

    def test_restore_wallpaper_reads_last_wall(self):
        self.last_wall.write_text(str(self.test_img.resolve()) + "\n", encoding="utf-8")
        run_mock = MagicMock(return_value=SimpleNamespace(returncode=0, stdout="", stderr=""))
        with patch.object(set_wallpaper, "ensure_awww_daemon", return_value=True), \
             patch.object(set_wallpaper.subprocess, "run", run_mock), \
             patch.dict(os.environ, {"HYPRLAND_INSTANCE_SIGNATURE": ""}):
            result = set_wallpaper.apply_wallpaper(
                restore=True,
                last_wall_path=self.last_wall,
                theme_json_path=self.theme_json,
                rofi_path=self.rofi_rasi,
            )

        self.assertTrue(result.get("ok"))
        # Verify transition-type none was passed for restore
        call_cmd = run_mock.call_args_list[0][0][0]
        self.assertEqual(call_cmd[:2], ["awww", "img"])
        self.assertIn("none", call_cmd)


if __name__ == "__main__":
    unittest.main()
